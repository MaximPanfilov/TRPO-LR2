"""Модуль арифметических операций.

Содержит базовые функции для сложения, вычитания, умножения,
деления и возведения в степень.
"""


def add(a, b):
    """Возвращает сумму двух чисел.

    Args:
        a: Первое слагаемое.
        b: Второе слагаемое.

    Returns:
        Результат сложения a + b.
    """
    return a + b


def subtract(a, b):
    """Возвращает разность двух чисел.

    Args:
        a: Уменьшаемое.
        b: Вычитаемое.

    Returns:
        Результат вычитания a - b.
    """
    return a - b


def multiply(a, b):
    """Возвращает произведение двух чисел.

    Args:
        a: Первый множитель.
        b: Второй множитель.

    Returns:
        Результат умножения a * b.
    """
    return a * b


def divide(a, b):
    """Возвращает частное от деления двух чисел.

    Args:
        a: Делимое.
        b: Делитель.

    Returns:
        Результат деления a / b.

    Raises:
        ValueError: Если b равно нулю.
    """
    if b == 0:
        raise ValueError("Деление на ноль невозможно")
    return a / b


def power(a, b):
    """Возводит число a в степень b.

    Args:
        a: Основание степени.
        b: Показатель степени.

    Returns:
        Результат возведения a в степень b.
    """
    return a ** b